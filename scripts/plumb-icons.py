def n(v):
    return ('%g' % v)


def r(x, y, w, h, rx=0, st=F):
    return f'<rect x="{n(x)}" y="{n(y)}" width="{n(w)}" height="{n(h)}"' + (f' rx="{n(rx)}"' if rx else '') + st + '/>'


def c(cx, cy, rad, st=F):
    return f'<circle cx="{n(cx)}" cy="{n(cy)}" r="{n(rad)}"{st}/>'


def e(cx, cy, rx, ry, st=F):
    return f'<ellipse cx="{n(cx)}" cy="{n(cy)}" rx="{n(rx)}" ry="{n(ry)}"{st}/>'


def p(d, st=''):
    return f'<path d="{d}"{st}/>'


def tube(d, w=6, core='F'):
    """Трубка: тёмный штрих шириной w и поверх сердцевина w-4 (светлая, цветная или вода)."""
    return (f'<path d="{d}" stroke-width="{n(w)}"/>'
            f'<path d="{d}" stroke-width="{n(w - 4)}" style="stroke:{CORE[core]}"/>')


def ring(cx, cy, rad, w=6, core='F'):
    d = f'M{n(cx - rad)} {n(cy)}a{n(rad)} {n(rad)} 0 1 0 {n(2 * rad)} 0a{n(rad)} {n(rad)} 0 1 0 {n(-2 * rad)} 0'
    return tube(d, w, core)


def drop(cx, cy, rad=2.2):
    top = cy - 1.9 * rad
    return p(f'M{n(cx)} {n(top)}C{n(cx + 0.5 * rad)} {n(cy - 1.1 * rad)} {n(cx + rad)} {n(cy - 0.5 * rad)} {n(cx + rad)} {n(cy)}'
             f'a{n(rad)} {n(rad)} 0 0 1 {n(-2 * rad)} 0c0 {n(-0.5 * rad)} {n(0.5 * rad)} {n(-0.9 * rad)} {n(rad)} {n(-1.9 * rad)}z', W)


def braid(d):
    return f'<path d="{d}" stroke-width="1" stroke-dasharray="1 2.5"/>'


def waves(y, x0=2, x1=46, st=WS):
    seg = []
    x = x0
    while x < x1:
        seg.append('q2-2.5 4 0' if not seg else 't4 0')
        x += 4
    return p(f'M{n(x0)} {n(y)}' + ''.join(seg), st)


# Корпус крана между гайками (y — верх, h — высота)
def valve_body(y=26, h=10, x0=4, x1=44):
    return [r(x0, y - 2, 7, h + 4, 1.5), r(x1 - 7, y - 2, 7, h + 4, 1.5), r(x0 + 6, y, x1 - x0 - 12, h, 2)]


ICONS = {}


def icon(name, words, *parts):
    flat = []
    for part in parts:
        flat.extend(part if isinstance(part, list) else [part])
    ICONS[name] = (words, flat)


