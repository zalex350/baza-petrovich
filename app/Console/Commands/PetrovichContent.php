    public function handle(): int
    {
        $force = (bool) $this->option('force');
        $values = Setting::values();
        $put = [];

        foreach (self::SETTINGS as $key => $value) {
            if ($force || $this->isEmpty($values[$key] ?? null)) {
                $put[$key] = $value;
            }
        }

        if ($force || ! Setting::phones()) {
            $put[Setting::PHONES] = json_encode(self::PHONES, JSON_UNESCAPED_UNICODE);
        }

        Setting::put($put);
        $this->info('Настроек заполнено: '.count($put));

        $pages = 0;

        foreach ($this->pages() as $slug => [$title, $body]) {
            $page = Page::firstOrNew(['slug' => $slug]);

            if (! $force && $page->exists && ! $this->isEmpty($page->body)) {
                continue;
            }

            $page->fill(['title' => $title, 'body' => $body, 'is_published' => true, 'type' => 'page'])->save();
            $pages++;
        }

        $this->info("Страниц заполнено: {$pages}");

        return self::SUCCESS;
    }

